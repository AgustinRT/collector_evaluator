

from sqlalchemy import BigInteger, Column, ForeignKey, Index, Integer, Sequence, String, Table, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from src.domain.model.collection import Collection
from src.infraestructure.persistence.entities.base import Base, use_sequence_as_postgres_default
from src.infraestructure.persistence.entities.item_collection_entity import ItemCollectionEntity
from src.infraestructure.persistence.entities.user_entity import UserEntity

COLLECTION_ID_SEQUENCE = Sequence("collection_seq", metadata=Base.metadata)

# Many-to-many link: a collection groups several items, and an item can be in several collections.
collection_items = Table(
    "collection_item",
    Base.metadata,
    Column(
        "collection_id",
        BigInteger,
        ForeignKey("collection.id", name="fk_collection_item_collection_id_collection", ondelete="CASCADE"),
        primary_key=True,
    ),
    Column(
        "item_id",
        BigInteger,
        ForeignKey("item_collection.id", name="fk_collection_item_item_id_item_collection"),
        primary_key=True,
    ),
    # The primary key serves lookups by collection; this index serves "collections that include an item".
    Index("ix_collection_item_item_id", "item_id"),
)


class CollectionEntity(Base):
    """
    Persistence representation of a Collection: linked to its owner through ``owner_id`` and to its items
    through ``collection_item``. On PostgreSQL the id is generated by the sequence ``collection_seq``.
    The PostgreSQL schema is defined in database/schema/schema.sql, which must match this entity.
    """
    __tablename__ = "collection"
    __table_args__ = (Index("ix_collection_owner_id", "owner_id"),)

    id: Mapped[int] = mapped_column(
        # SQLite (in-memory fallback) has no sequences: only an INTEGER primary key auto-increments.
        BigInteger().with_variant(Integer, "sqlite"),
        COLLECTION_ID_SEQUENCE,
        primary_key=True,
    )
    owner_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("user.id", name="fk_collection_owner_id_user"), nullable=False,
    )
    name: Mapped[str] = mapped_column(String(200), nullable=False)
    description: Mapped[str] = mapped_column(Text, nullable=False)

    owner: Mapped[UserEntity] = relationship()
    # A collection is always read with its items: "selectin" loads the items of all the collections of a
    # query in one extra query, instead of one query per collection.
    items: Mapped[list[ItemCollectionEntity]] = relationship(
        secondary=collection_items, order_by=ItemCollectionEntity.id, lazy="selectin",
    )

    @classmethod
    def from_domain(
        cls, collection: Collection, owner: UserEntity, items: list[ItemCollectionEntity],
    ) -> "CollectionEntity":
        """
        :param owner: the stored owner; its id becomes the collection's ``owner_id``.
        :param items: the stored items of the collection.
        """
        return cls(owner=owner, items=items, name=collection.name, description=collection.description)

    def to_domain(self) -> Collection:
        return Collection(
            id=self.id,
            name=self.name,
            description=self.description,
            owner=self.owner.to_domain(),
            items=[item.to_domain() for item in self.items],
        )


use_sequence_as_postgres_default(CollectionEntity.__table__, "id", COLLECTION_ID_SEQUENCE)
