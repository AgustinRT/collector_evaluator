

from sqlalchemy import BigInteger, CheckConstraint, Double, Enum, Integer, Sequence, String, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column

from src.domain.enum.user_status import UserStatus
from src.domain.model.location import Location
from src.domain.model.user import User
from src.infraestructure.persistence.entities.base import Base, use_sequence_as_postgres_default

USER_ID_SEQUENCE = Sequence("user_seq", metadata=Base.metadata)


class UserEntity(Base):
    """
    Persistence representation of a User (table "user", a reserved word that SQLAlchemy always quotes).
    On PostgreSQL the id is generated by the sequence ``user_seq``; the application never assigns it.
    The PostgreSQL schema is defined in database/schema/schema.sql, which must match this entity.
    """
    __tablename__ = "user"
    __table_args__ = (
        UniqueConstraint("username", name="uq_user_username"),
        # The location is optional, but when stored it must be complete and within range.
        CheckConstraint("(latitude IS NULL) = (longitude IS NULL)", name="ck_user_location_complete"),
        CheckConstraint("latitude BETWEEN -90 AND 90", name="ck_user_latitude_range"),
        CheckConstraint("longitude BETWEEN -180 AND 180", name="ck_user_longitude_range"),
    )

    id: Mapped[int] = mapped_column(
        # SQLite (in-memory fallback) has no sequences: only an INTEGER primary key auto-increments.
        BigInteger().with_variant(Integer, "sqlite"),
        USER_ID_SEQUENCE,
        primary_key=True,
    )
    username: Mapped[str] = mapped_column(String(150), nullable=False)
    # 254 is the maximum length of a valid email address (RFC 5321), enforced by the domain's EmailStr.
    email: Mapped[str] = mapped_column(String(254), nullable=False)
    latitude: Mapped[float | None] = mapped_column(Double, nullable=True)
    longitude: Mapped[float | None] = mapped_column(Double, nullable=True)
    status: Mapped[UserStatus] = mapped_column(
        Enum(UserStatus, name="user_status", values_callable=lambda enum: [member.value for member in enum]),
        nullable=False,
    )
    evaluation: Mapped[float] = mapped_column(Double, nullable=False)

    @classmethod
    def from_domain(cls, user: User) -> "UserEntity":
        return cls(
            username=user.username,
            email=user.email,
            latitude=user.location.latitude if user.location is not None else None,
            longitude=user.location.longitude if user.location is not None else None,
            status=user.status,
            evaluation=user.evaluation,
        )

    def to_domain(self) -> User:
        location = None
        if self.latitude is not None and self.longitude is not None:
            location = Location(latitude=self.latitude, longitude=self.longitude)
        return User(
            username=self.username,
            email=self.email,
            location=location,
            status=self.status,
            evaluation=self.evaluation,
        )


use_sequence_as_postgres_default(UserEntity.__table__, "id", USER_ID_SEQUENCE)
