

from sqlalchemy import BigInteger, CheckConstraint, Enum, ForeignKey, Index, Integer, Sequence, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from src.domain.enum.item_status import ItemStatus
from src.domain.model.item_collection import GTIN_MAX_DIGITS, ItemCollection
from src.infraestructure.persistence.entities.base import Base, use_sequence_as_postgres_default
from src.infraestructure.persistence.entities.user_entity import UserEntity

ITEM_COLLECTION_ID_SEQUENCE = Sequence("item_collection_seq", metadata=Base.metadata)


class ItemCollectionEntity(Base):
    """
    Persistence representation of an ItemCollection, linked to its owner through ``owner_id``.
    On PostgreSQL the id is generated by the sequence ``item_collection_seq``.
    The PostgreSQL schema is defined in database/schema/schema.sql, which must match this entity.
    """
    __tablename__ = "item_collection"
    __table_args__ = (
        CheckConstraint(f"barcode > 0 AND barcode < {10**GTIN_MAX_DIGITS}", name="ck_item_collection_barcode_range"),
        # Items are always listed by owner.
        Index("ix_item_collection_owner_id", "owner_id"),
    )

    id: Mapped[int] = mapped_column(
        # SQLite (in-memory fallback) has no sequences: only an INTEGER primary key auto-increments.
        BigInteger().with_variant(Integer, "sqlite"),
        ITEM_COLLECTION_ID_SEQUENCE,
        primary_key=True,
    )
    owner_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("user.id", name="fk_item_collection_owner_id_user"), nullable=False,
    )
    name: Mapped[str] = mapped_column(String(200), nullable=False)
    description: Mapped[str] = mapped_column(Text, nullable=False)
    barcode: Mapped[int] = mapped_column(BigInteger, nullable=False)
    status: Mapped[ItemStatus] = mapped_column(
        Enum(ItemStatus, name="item_status", values_callable=lambda enum: [member.value for member in enum]),
        nullable=False,
    )

    owner: Mapped[UserEntity] = relationship()

    @classmethod
    def from_domain(cls, item: ItemCollection, owner: UserEntity) -> "ItemCollectionEntity":
        """
        :param owner: the stored owner; its id becomes the item's ``owner_id``.
        """
        return cls(
            owner=owner,
            name=item.name,
            description=item.description,
            barcode=item.barcode,
            status=item.status,
        )

    def to_domain(self) -> ItemCollection:
        return ItemCollection(
            id=self.id,
            name=self.name,
            description=self.description,
            barcode=self.barcode,
            status=self.status,
            owner=self.owner.to_domain(),
        )


use_sequence_as_postgres_default(ItemCollectionEntity.__table__, "id", ITEM_COLLECTION_ID_SEQUENCE)
